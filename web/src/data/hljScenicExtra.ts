// 景区名录演示数据的组装层。
// - hljScenicRows()：省文旅厅官方名录 438 行（xlsx 原件转换，保持原文不动）
// - 本文件做两件事：
//   1) 给每一行补一列「所在省份」（常量"黑龙江省"——事实如此，方便和其他黑龙江表
//      结构统一，并让默认清洗方案自动勾上「地区别名」规则）
//   2) 追加 14 行「多来源补报」风格的演示脏数据（见下方函数注释，非官方名录内容），
//      精准命中默认清洗方案里的 trim / 地区别名 / 空值统一 / 整行去重 四类规则。
export function hljScenicAllRows(): DataRow[] {
  return [
    ...hljScenicRows().map((row) => ({
      ...row,
      values: { 所在省份: "黑龙江省", ...row.values },
    })),
    ...hljScenicExtraRows(),
  ];
}

