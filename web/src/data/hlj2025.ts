//   2023-2024 雪季 8743.8 万人次 / 1248.9 亿元（同比 +301.5% / +505.5%，"尔滨"出圈季）；
//   2024-2025 雪季 9035.7 万人次 / 1372.2 亿元（同比 +9.7% / +16.6%，入境游客 +94.2%）。
//   2022-2023 雪季为按官方同比增速反推的约数（≈2178 万人次 / ≈206.2 亿元），仅用于体现趋势。

