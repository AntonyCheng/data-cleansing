// - 经济指标（GDP、人均GDP、占全省比重）：2024 年数据，《黑龙江统计年鉴－2025》，中国统计出版社
// - 人口指标（常住人口、户籍人口、城镇化率、人口密度）：黑龙江省统计局、
//   黑龙江省第七次全国人口普查领导小组办公室《2020年黑龙江省第七次全国人口普查主要数据公报》
// 两份数据年份不同（经济是 2024、人口普查是 2020，十年一次），字段名里标出了年份，不混成一年。
// "所属省份"一列故意掺入几种常见写法（黑龙江/黑龍江/HLJ），配合 engine.ts 里已经内置的
// "地区别名"清洗规则（就是拿黑龙江当示例写的）；末尾追加一行重复数据，模拟报送重复，用于演示去重。
export function heilongjiangCityRows(): DataRow[] {
  const cities: [string, string, number, number, number, number, number, number, number][] = [
    // 地市, 所属省份, GDP亿元, 人均GDP元, 占全省比重%, 常住人口2020, 户籍人口2020, 城镇化率%, 人口密度
    ["哈尔滨市", "黑龙江省", 6016.3, 61266, 36.38, 10009854, 9485492, 70.61, 188.4],
    ["齐齐哈尔市", "黑龙江", 1353.1, 35656, 8.18, 4067489, 5220752, 53.64, 95.5],
    ["大庆市", "黑龙江省", 2815.8, 105066, 17.03, 2781562, 2735320, 72.48, 131.1],
    ["绥化市", "黑龙江省", 1244.0, 35441, 7.52, 3756167, 5180805, 43.66, 106.6],
    ["牡丹江市", "黑龙江省", 1051.4, 47789, 6.36, 2290208, 2472355, 65.81, 58.7],
    ["佳木斯市", "HLJ", 1007.7, 48565, 6.09, 2156505, 2302124, 65.17, 66.2],
    ["黑河市", "黑龙江省", 711.4, 58312, 4.3, 1286401, 1555210, 65.21, 19.1],
    ["鸡西市", "黑龙江省", 622.6, 44157, 3.77, 1502060, 1670345, 72.68, 66.4],
    ["双鸭山市", "黑龙江省", 557.4, 48898, 3.37, 1208803, 1384439, 68.39, 54.6],
    ["鹤岗市", "黑龍江", 376.3, 44800, 2.28, 891271, 970042, 82.63, 60.5],
    ["伊春市", "黑龙江省", 370.5, 45456, 2.24, 878881, 1102950, 84.65, 26.6],
    ["七台河市", "黑龙江省", 236.6, 36119, 1.43, 689611, 760669, 77.16, 110.7],
    ["大兴安岭地区", "黑龙江省", 173.1, 56741, 1.05, 331276, 407062, 93.57, 3.9],
  ];
  const rows: DataRow[] = cities.map(([city, province, gdp, gdpPerCapita, share, pop, householdPop, urbanRate, density], i) => ({
    id: `hlj-${i + 1}`,
    values: {
      地市: city,
      所属省份: province,
      // 哈尔滨市数值最大，故意用千分位格式，模拟真实报表里常见的格式不统一
      地区生产总值_亿元: i === 0 ? gdp.toLocaleString("en-US") : String(gdp),
      人均GDP_元: String(gdpPerCapita),
      占全省比重_百分比: String(share),
      常住人口_2020年七普: String(pop),
      户籍人口_2020年末: String(householdPop),
      城镇化率_百分比: String(urbanRate),
      人口密度_人每平方公里: String(density),
    },
  }));
  // 模拟报送重复：追加一行与佳木斯市完全相同的记录
  rows.push({ id: "hlj-dup-1", values: { ...rows[5].values } });
  return rows;
}
